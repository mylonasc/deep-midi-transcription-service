"""Storage interfaces. Implementations live in sqlite.py / local.py."""
from __future__ import annotations

from pathlib import Path
from typing import Protocol

from ..models import Job, JobStatus


class MetadataStore(Protocol):
    async def init(self) -> None: ...
    async def create(self, job: Job) -> Job: ...
    async def get(self, job_id: str) -> Job | None: ...
    async def list(self, status: JobStatus | None = None, limit: int = 100, offset: int = 0) -> list[Job]: ...
    async def update(self, job: Job) -> Job: ...
    async def delete(self, job_id: str) -> None: ...


class ObjectStore(Protocol):
    async def put_bytes(self, key: str, data: bytes) -> None: ...
    async def put_path(self, key: str, src: Path) -> None: ...
    async def get_bytes(self, key: str) -> bytes | None: ...
    async def get_path(self, key: str) -> Path | None: ...
    async def delete_prefix(self, prefix: str) -> None: ...
